//! OAuth 2.0 PKCE flow implementation for ChatGPT authentication.
//!
//! ## Flow summary
//!
//! 1. [`build_authorization_flow`] — generate a PKCE verifier/challenge pair,
//!    a random state token, and construct the authorization URL.
//! 2. The caller opens the URL in a browser. The user logs in and grants
//!    consent on ChatGPT's side.
//! 3. ChatGPT redirects the browser to the local callback server
//!    ([`callback::wait_for_authorization_code`]).
//! 4. [`exchange_authorization_code`] sends the code and PKCE verifier to the
//!    token endpoint and returns a [`TokenStore`].
//! 5. [`refresh_access_token`] can be used on subsequent startups to renew an
//!    expiring or expired access token without re-running the browser flow.

mod callback;

use anyhow::{Context, Result};
use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
use reqwest::Client;
use serde::Deserialize;
use sha2::{Digest, Sha256};
use tracing::{info, warn};
use url::Url;
use uuid::Uuid;

use crate::{
    config::UpstreamConfig, constants::CALLBACK_PATH, state::TokenStore, time::unix_timestamp_secs,
};

pub use callback::wait_for_authorization_code;

/// All data generated by [`build_authorization_flow`] that must be kept in
/// memory (or persisted to `state.json`) until the authorization code arrives.
#[derive(Debug, Clone)]
pub struct AuthorizationFlow {
    /// Random UUID used as the OAuth `state` parameter for CSRF protection.
    pub state: String,
    /// PKCE verifier (random bytes, base64url-encoded). Sent to the token
    /// endpoint alongside the authorization code.
    pub pkce_verifier: String,
    /// SHA-256 hash of `pkce_verifier`, base64url-encoded. Sent in the
    /// authorization URL so the server can verify the verifier later.
    pub code_challenge: String,
    /// Full authorization URL to open in the browser.
    pub authorize_url: String,
}

/// Raw token response from the OAuth token endpoint.
#[derive(Debug, Deserialize)]
struct OAuthTokenResponse {
    access_token: String,
    refresh_token: String,
    /// Lifetime of `access_token` in seconds, used to compute `expires_at`.
    expires_in: i64,
    #[serde(default = "default_token_type")]
    token_type: String,
    #[serde(default)]
    scope: String,
}

/// Build an [`AuthorizationFlow`] ready for browser redirect.
///
/// Generates a fresh PKCE pair and appends all required query parameters
/// (including the ChatGPT-specific `id_token_add_organizations`,
/// `codex_cli_simplified_flow`, and `originator` flags).
pub fn build_authorization_flow(
    upstream: &UpstreamConfig,
    redirect_uri: &str,
) -> Result<AuthorizationFlow> {
    let state = Uuid::new_v4().simple().to_string();
    let pkce_verifier = create_pkce_verifier();
    let code_challenge = create_code_challenge(&pkce_verifier);

    let mut authorize_url =
        Url::parse(&upstream.authorize_url).context("invalid OAuth authorize URL")?;
    authorize_url
        .query_pairs_mut()
        .append_pair("response_type", "code")
        .append_pair("client_id", &upstream.client_id)
        .append_pair("redirect_uri", redirect_uri)
        .append_pair("scope", &upstream.scope)
        .append_pair("code_challenge", &code_challenge)
        .append_pair("code_challenge_method", "S256")
        .append_pair("state", &state)
        .append_pair("id_token_add_organizations", "true")
        .append_pair("codex_cli_simplified_flow", "true")
        .append_pair("originator", &upstream.originator);

    Ok(AuthorizationFlow {
        state,
        pkce_verifier,
        code_challenge,
        authorize_url: authorize_url.to_string(),
    })
}

/// Exchange an authorization `code` for access and refresh tokens.
///
/// Called once after the local callback server receives the redirect from
/// ChatGPT. Uses the `authorization_code` grant type.
pub async fn exchange_authorization_code(
    client: &Client,
    upstream: &UpstreamConfig,
    code: &str,
    pkce_verifier: &str,
    redirect_uri: &str,
) -> Result<TokenStore> {
    request_tokens(
        client,
        upstream,
        vec![
            ("grant_type", "authorization_code".to_owned()),
            ("client_id", upstream.client_id.clone()),
            ("code", code.to_owned()),
            ("code_verifier", pkce_verifier.to_owned()),
            ("redirect_uri", redirect_uri.to_owned()),
        ],
    )
    .await
}

/// Obtain a new access token using a stored refresh token.
///
/// Uses the `refresh_token` grant type. Called on daemon startup and during
/// request forwarding when the stored token is expiring or expired.
pub async fn refresh_access_token(
    client: &Client,
    upstream: &UpstreamConfig,
    refresh_token: &str,
) -> Result<TokenStore> {
    request_tokens(
        client,
        upstream,
        vec![
            ("grant_type", "refresh_token".to_owned()),
            ("client_id", upstream.client_id.clone()),
            ("refresh_token", refresh_token.to_owned()),
        ],
    )
    .await
}

/// Shared implementation for both token grant types.
///
/// Posts `form_fields` to the token endpoint, validates the response status,
/// parses the JSON body, and extracts the ChatGPT account ID from the JWT
/// payload before returning a [`TokenStore`].
async fn request_tokens(
    client: &Client,
    upstream: &UpstreamConfig,
    form_fields: Vec<(&str, String)>,
) -> Result<TokenStore> {
    let response = client
        .post(&upstream.token_url)
        .form(&form_fields)
        .send()
        .await
        .context("failed to reach the OAuth token endpoint")?;

    let status = response.status();
    if !status.is_success() {
        let body = response.text().await.unwrap_or_default();
        let body = body.trim();
        warn!(
            status = %status,
            body_snippet = %truncate_log_body(body),
            "OAuth token endpoint returned a non-success response"
        );
        let detail = if body.is_empty() {
            format!("OAuth token request failed with status {status}")
        } else {
            format!("OAuth token request failed with status {status}: {body}")
        };
        anyhow::bail!(detail);
    }

    let token_response: OAuthTokenResponse = response
        .json()
        .await
        .context("failed to parse the OAuth token response")?;
    let obtained_at = unix_timestamp_secs();
    info!(
        expires_in = token_response.expires_in,
        scope = %token_response.scope,
        "received OAuth token response successfully"
    );

    Ok(TokenStore {
        account_id: decode_jwt_account_id(&token_response.access_token)?,
        access_token: token_response.access_token,
        refresh_token: token_response.refresh_token,
        expires_at: obtained_at + token_response.expires_in,
        token_type: token_response.token_type,
        scope: token_response.scope,
        obtained_at,
    })
}

/// Extract the `chatgpt_account_id` from the JWT access token without
/// verifying the signature.
///
/// The account ID lives in a custom claim at
/// `"https://api.openai.com/auth".chatgpt_account_id`. It must be forwarded
/// in the `chatgpt-account-id` upstream request header.
///
/// Returns `Ok(None)` when the claim is absent rather than an error, because
/// its absence should surface as a forwarding error rather than an auth error.
pub fn decode_jwt_account_id(token: &str) -> Result<Option<String>> {
    let mut parts = token.split('.');
    let _header = parts.next();
    let payload = match parts.next() {
        Some(value) => value,
        None => return Ok(None),
    };

    let decoded = URL_SAFE_NO_PAD
        .decode(payload.as_bytes())
        .context("failed to decode JWT payload")?;
    let payload: serde_json::Value =
        serde_json::from_slice(&decoded).context("failed to parse JWT payload")?;

    Ok(payload
        .get("https://api.openai.com/auth")
        .and_then(|value| value.get("chatgpt_account_id"))
        .and_then(|value| value.as_str())
        .map(ToOwned::to_owned))
}

/// Construct the full OAuth `redirect_uri` for the local callback server.
pub fn callback_url(host: &str, port: u16) -> String {
    format!("http://{host}:{port}{CALLBACK_PATH}")
}

/// Generate a 256-bit PKCE verifier encoded as base64url (no padding).
///
/// Two random UUIDs are concatenated to produce 32 bytes of entropy and then
/// base64url-encoded, satisfying the RFC 7636 length requirements.
fn create_pkce_verifier() -> String {
    let mut raw = Vec::with_capacity(32);
    raw.extend_from_slice(Uuid::new_v4().as_bytes());
    raw.extend_from_slice(Uuid::new_v4().as_bytes());
    URL_SAFE_NO_PAD.encode(raw)
}

/// Derive the PKCE code challenge from the verifier using S256.
///
/// `code_challenge = BASE64URL(SHA256(ASCII(code_verifier)))` per RFC 7636.
fn create_code_challenge(pkce_verifier: &str) -> String {
    let digest = Sha256::digest(pkce_verifier.as_bytes());
    URL_SAFE_NO_PAD.encode(digest)
}

fn default_token_type() -> String {
    "Bearer".to_owned()
}

fn truncate_log_body(body: &str) -> String {
    const MAX_CHARS: usize = 256;
    let compact = body.split_whitespace().collect::<Vec<_>>().join(" ");
    if compact.chars().count() <= MAX_CHARS {
        compact
    } else {
        let truncated = compact.chars().take(MAX_CHARS).collect::<String>();
        format!("{truncated}...[truncated]")
    }
}

#[cfg(test)]
mod tests {
    use std::net::SocketAddr;

    use axum::{Json, Router, routing::post};
    use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
    use serde_json::json;
    use tokio::net::TcpListener;

    use super::*;

    #[test]
    fn build_authorization_flow_uses_expected_parameters() {
        let upstream = UpstreamConfig::default();
        let redirect_uri = "http://localhost:1455/auth/callback";

        let flow = build_authorization_flow(&upstream, redirect_uri).expect("flow");
        let url = Url::parse(&flow.authorize_url).expect("url");

        assert_eq!(url.path(), "/oauth/authorize");
        assert_eq!(
            url.query_pairs()
                .find(|(key, _)| key == "response_type")
                .map(|(_, value)| value.to_string())
                .as_deref(),
            Some("code")
        );
        assert_eq!(
            url.query_pairs()
                .find(|(key, _)| key == "client_id")
                .map(|(_, value)| value.to_string())
                .as_deref(),
            Some(upstream.client_id.as_str())
        );
        assert_eq!(
            url.query_pairs()
                .find(|(key, _)| key == "redirect_uri")
                .map(|(_, value)| value.to_string())
                .as_deref(),
            Some(redirect_uri)
        );
        assert_eq!(
            url.query_pairs()
                .find(|(key, _)| key == "originator")
                .map(|(_, value)| value.to_string())
                .as_deref(),
            Some(upstream.originator.as_str())
        );
        assert!(!flow.pkce_verifier.is_empty());
        assert!(!flow.code_challenge.is_empty());
    }

    #[test]
    fn decode_jwt_account_id_reads_chatgpt_account() {
        let payload = json!({
            "https://api.openai.com/auth": {
                "chatgpt_account_id": "account-123"
            }
        });
        let token = format!(
            "header.{}.signature",
            URL_SAFE_NO_PAD.encode(serde_json::to_vec(&payload).expect("payload"))
        );

        let account_id = decode_jwt_account_id(&token).expect("account id");

        assert_eq!(account_id.as_deref(), Some("account-123"));
    }

    #[tokio::test]
    async fn refresh_access_token_reads_and_normalizes_token_response() {
        let account_payload = json!({
            "https://api.openai.com/auth": {
                "chatgpt_account_id": "account-456"
            }
        });
        let access_token = format!(
            "header.{}.signature",
            URL_SAFE_NO_PAD.encode(serde_json::to_vec(&account_payload).expect("payload"))
        );

        let listener = TcpListener::bind("127.0.0.1:0").await.expect("listener");
        let addr: SocketAddr = listener.local_addr().expect("addr");
        async fn token_handler(access_token: String) -> Json<serde_json::Value> {
            Json(json!({
                "access_token": access_token,
                "refresh_token": "new-refresh-token",
                "expires_in": 3600,
                "token_type": "Bearer",
                "scope": "openid profile email offline_access"
            }))
        }
        let app = Router::new().route(
            "/oauth/token",
            post(move || token_handler(access_token.clone())),
        );
        let server = tokio::spawn(async move {
            axum::serve(listener, app).await.expect("serve");
        });

        let upstream = UpstreamConfig {
            token_url: format!("http://{addr}/oauth/token"),
            ..UpstreamConfig::default()
        };

        let tokens = refresh_access_token(&Client::new(), &upstream, "old-refresh-token")
            .await
            .expect("refresh tokens");

        assert_eq!(tokens.refresh_token, "new-refresh-token");
        assert_eq!(tokens.account_id.as_deref(), Some("account-456"));
        assert_eq!(tokens.scope, "openid profile email offline_access");
        assert!(tokens.expires_at > tokens.obtained_at);

        server.abort();
    }
}
